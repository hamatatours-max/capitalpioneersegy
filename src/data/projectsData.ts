export const filterProjects = (filters: Partial<ProjectFilterState>): Project[] => {
  return PROJECTS_DATABASE.filter((p) => {
    // Keyword search across title, developer, location, area, description, amenities
    if (filters.searchQuery && filters.searchQuery.trim() !== '') {
      const q = filters.searchQuery.toLowerCase();
      const matchName = p.name.toLowerCase().includes(q);
      const matchLocation = p.location.toLowerCase().includes(q);
      const matchArea = p.area.toLowerCase().includes(q);
      const matchDev = p.developer.toLowerCase().includes(q);
      const matchDesc = p.shortDescription.toLowerCase().includes(q) || p.fullDescription.toLowerCase().includes(q);
      const matchType = p.projectType.toLowerCase().includes(q);
      const matchAmenities = p.amenities.some((a) => a.toLowerCase().includes(q));
      if (!matchName && !matchLocation && !matchArea && !matchDev && !matchDesc && !matchType && !matchAmenities) {
        return false;
      }
    }

    // Governorate filter
    if (filters.governorate && filters.governorate !== 'All' && p.governorate !== filters.governorate) {
      return false;
    }

    // Area filter
    if (filters.area && filters.area !== 'All' && p.area !== filters.area) {
      return false;
    }

    // Project Type filter
    if (filters.projectType && filters.projectType !== 'All' && p.projectType !== filters.projectType) {
      return false;
    }

    // Property Type filter
    if (
      filters.propertyType &&
      filters.propertyType !== 'All' &&
      !p.propertyTypes.includes(filters.propertyType as PropertyType)
    ) {
      return false;
    }

    // Project Status filter
    if (filters.projectStatus && filters.projectStatus !== 'All' && p.projectStatus !== filters.projectStatus) {
      return false;
    }

    // Featured only
    if (filters.featuredOnly && !p.featured) {
      return false;
    }

    // Red Sea only
    if (filters.redSeaOnly && !p.isRedSea && !p.redSeaProject) {
      return false;
    }

    return true;
  });
};
